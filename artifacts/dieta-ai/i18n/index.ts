const translations: Record<Language, TranslationMap> = {
  "uz": uz,
  "uz-kril": uzKril,
  "ru": ru,
};

export function translate(lang: Language, key: string, params?: Record<string, string | number>): string {
  const map = translations[lang] ?? translations["uz"];
  let str = map[key] ?? translations["uz"][key] ?? key;
  if (params) {
    str = Object.entries(params).reduce(
      (s, [k, v]) => s.replace(`{${k}}`, String(v)),
      str,
    );
  }
  return str;
}

